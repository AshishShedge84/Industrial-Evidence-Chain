export const EmptyState = forwardRef<HTMLDivElement, EmptyStateProps>(
  ({ className = '', icon, title, description, action, illustration, children, ...props }, ref) => {
    const Icon = illustration ? illustrations[illustration] : null;

    return (
      <div
        ref={ref}
        className={`flex flex-col items-center justify-center text-center py-12 px-4 ${className}`}
        {...props}
      >
        {icon ? (
          <div className="flex-shrink-0 mb-4 text-gray-300">{icon}</div>
        ) : Icon ? (
          <div className="flex-shrink-0 mb-4">{Icon}</div>
        ) : null}
        <h3 className="text-lg font-semibold text-gray-900 dark:text-gray-100">{title}</h3>
        {description && (
          <p className="mt-2 text-sm text-gray-500 dark:text-gray-400 max-w-md">{description}</p>
        )}
        {action && (
          <div className="mt-6">
            <Button variant={action.variant ?? 'primary'} onClick={action.onClick}>
              {action.label}
            </Button>
          </div>
        )}
        {children}
      </div>
    );
  }
);

EmptyState.displayName = 'EmptyState';